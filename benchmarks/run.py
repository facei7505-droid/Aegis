"""Reproducible benchmarks. Writes BENCHMARKS.md next to the README.

    python benchmarks/run.py                 # shield + scanner + self-healing demo
    python benchmarks/run.py --real-world    # also measure noise on installed packages
"""
from __future__ import annotations

import argparse
import statistics
import sys
import time
from collections import Counter
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent))

from aegis import __version__  # noqa: E402
from aegis.shield.detectors import score_all  # noqa: E402

THRESHOLD = 0.8


def shield_bench():
    attacks = [line.split("\t", 1) for line in (HERE / "data" / "attacks.tsv").read_text(encoding="utf-8").splitlines() if line.strip()]
    benign = [line.replace("\\n", "\n") for line in (HERE / "data" / "benign.txt").read_text(encoding="utf-8").splitlines() if line.strip()]
    per_class = Counter()
    hit_class = Counter()
    misses, wrong_class, false_pos = [], [], []
    timings = []
    for expected, payload in attacks:
        t0 = time.perf_counter()
        attack, score, _, classes = score_all(payload)
        timings.append((time.perf_counter() - t0) * 1e6)
        per_class[expected] += 1
        if score >= THRESHOLD:
            hit_class[expected] += 1
            if classes.get(expected, 0) < 0.5:
                wrong_class.append((expected, attack, payload))
        else:
            misses.append((expected, payload, score))
    for text in benign:
        t0 = time.perf_counter()
        attack, score, signals, _ = score_all(text)
        timings.append((time.perf_counter() - t0) * 1e6)
        if score >= THRESHOLD:
            false_pos.append((text, attack, signals))
    return {
        "attacks": len(attacks), "benign": len(benign),
        "detected": sum(hit_class.values()), "false_positives": false_pos, "misses": misses,
        "wrong_class": wrong_class, "per_class": per_class, "hit_class": hit_class,
        "median_us": statistics.median(timings), "p99_us": sorted(timings)[int(len(timings) * 0.99) - 1],
    }


def heldout_bench():
    """Inputs written after the detectors were tuned and never used to change them."""
    attacks = [line.split("\t", 1) for line in (HERE / "data" / "heldout_attacks.tsv").read_text(encoding="utf-8").splitlines() if line.strip()]
    benign = [line for line in (HERE / "data" / "heldout_benign.txt").read_text(encoding="utf-8").splitlines() if line.strip()]
    missed = [p.replace("\\n", "\n") for _, p in attacks if score_all(p.replace("\\n", "\n"))[1] < THRESHOLD]
    flagged = [b for b in benign if score_all(b)[1] >= THRESHOLD]
    return {"attacks": len(attacks), "missed": missed, "benign": len(benign), "flagged": flagged}


def demo_bench():
    from aegis.demo import run_demo
    import tempfile

    result = run_demo(tempfile.mkdtemp(prefix="aegis-bench-"), log=lambda *_: None)
    return result


def real_world_bench(root: str, limit: int):
    from aegis.config import TEST_FILES
    from aegis.patcher.engine import fix_file
    from aegis.scanner.engine import iter_python_files, scan_source

    files, findings, sev, fixed, crashes = 0, 0, Counter(), 0, 0
    t0 = time.perf_counter()
    for f in iter_python_files(root, TEST_FILES):
        files += 1
        try:
            found = scan_source(str(f))
        except Exception:
            continue
        findings += len(found)
        sev.update(x.severity for x in found)
        if any(x.fixable for x in found):
            try:
                fixed += len(fix_file(str(f), write=False).patches)
            except Exception:
                crashes += 1
        if files >= limit:
            break
    return {"files": files, "findings": findings, "severity": sev, "auto_patches": fixed, "crashes": crashes,
            "seconds": round(time.perf_counter() - t0, 1)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--real-world", nargs="?", const=str(Path(sys.prefix) / "lib"), default=None)
    ap.add_argument("--limit", type=int, default=10_000)
    args = ap.parse_args()

    s = shield_bench()
    h = heldout_bench()
    d = demo_bench()
    ds = d.summary()
    tpr = s["detected"] / s["attacks"] * 100
    fpr = len(s["false_positives"]) / s["benign"] * 100

    lines = [
        f"# Aegis v{__version__} — benchmarks",
        "",
        f"Generated by `python benchmarks/run.py` on Python {sys.version.split()[0]}. Every number below is reproducible.",
        "",
        "## 1. Shield: attack detection",
        "",
        f"- Attack corpus: **{s['attacks']} payloads** in 7 classes, including URL/double-URL/HTML-entity encoding, "
        "mixed case and SQL comment padding (`benchmarks/data/attacks.tsv`).",
        f"- Benign corpus: **{s['benign']} real-world inputs** that trip naive filters: `O'Brien`, `rock & roll`, "
        "`C#`, `<3`, Kazakh/Russian addresses, code snippets from support tickets (`benchmarks/data/benign.txt`).",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Detection rate | **{tpr:.1f}%** ({s['detected']}/{s['attacks']}) |",
        f"| False-positive rate | **{fpr:.1f}%** ({len(s['false_positives'])}/{s['benign']}) |",
        f"| Median inspection time per value | {s['median_us']:.0f} µs |",
        f"| p99 inspection time per value | {s['p99_us']:.0f} µs |",
        "",
        "> Honest caveat: both corpora are small and were used while the detectors were written (they include",
        "> every bypass and false positive found by an independent review), so these numbers are an upper bound.",
        "",
        "**Held-out check.** After tuning, a second set was written and frozen: it is never used to change the",
        "detectors (`benchmarks/data/heldout_*`).",
        "",
        "| Held-out metric | Value |",
        "| --- | --- |",
        f"| Attacks detected | **{h['attacks'] - len(h['missed'])}/{h['attacks']}** |",
        f"| Benign inputs flagged | **{len(h['flagged'])}/{h['benign']}** |",
        "",
    ]
    if h["missed"]:
        lines += ["Held-out misses: " + ", ".join(f"`{m}`" for m in h["missed"]) + ". A signature WAF is one layer: "
                  "these are why Aegis also fixes the code itself.", ""]
    if h["flagged"]:
        lines += ["Held-out false positives: " + ", ".join(f"`{b}`" for b in h["flagged"]) + ".", ""]
    lines += [
        "| Attack class | Detected |",
        "| --- | --- |",
    ]
    for cls in sorted(s["per_class"]):
        lines.append(f"| {cls} | {s['hit_class'][cls]}/{s['per_class'][cls]} |")
    if s["misses"]:
        lines += ["", "Missed payloads (published on purpose — known gaps to close next):", ""]
        lines += [f"- `{cls}` — `{p}` (score {sc:.2f})" for cls, p, sc in s["misses"]]
    if s["false_positives"]:
        lines += ["", "False positives:", ""] + [f"- `{t}` → {a} ({', '.join(sig)})" for t, a, sig in s["false_positives"]]

    lines += [
        "",
        "## 2. Self-healing loop (VulnShop)",
        "",
        "Real attacks against a deliberately vulnerable Flask shop, then the same attacks replayed after healing "
        "**without** the shield in front.",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Vulnerabilities found by the scanner | {ds['vulnerabilities_found']} |",
        f"| Attacks that worked before | {ds['exploitable_before']}/{ds['attacks_total']} |",
        f"| Attacks blocked by the shield | {ds['attacks_blocked']}/{ds['attacks_total']} |",
        f"| Incidents traced to the vulnerable line and patched | {ds['incidents_healed']}/{ds['attacks_total']} |",
        f"| Mean time from attack to verified patch | **{ds['mean_heal_ms']} ms** |",
        f"| Attacks that still work after healing | **{ds['exploitable_after']}/{ds['attacks_total']}** |",
        f"| Legitimate requests working after healing | {ds['checks_passing_after']}/{ds['checks_total']} "
        f"(before: {ds['checks_passing_before']}/{ds['checks_total']}) |",
        f"| False positives on legitimate requests | {ds['false_positives']} |",
        f"| Findings left for a human (rules only) | {ds['remaining_findings']} — MD5 password hashing and pickle "
        "need a data migration, so Aegis refuses to guess |",
    ]

    if args.real_world:
        r = real_world_bench(args.real_world, args.limit)
        sev = ", ".join(f"{n} {k}" for k, n in sorted(r["severity"].items()))
        lines += [
            "",
            "## 3. Noise on real-world code",
            "",
            f"Scanned **{r['files']} files** of installed open-source packages (tests excluded) in {r['seconds']} s. "
            "These are libraries, not web apps: a good scanner should stay quiet and must never break their code.",
            "",
            "| Metric | Value |",
            "| --- | --- |",
            f"| Findings | {r['findings']} ({sev or 'none'}) |",
            f"| Automatic patches applied | {r['auto_patches']} (Aegis only auto-patches code reachable from HTTP input) |",
            f"| Crashes | {r['crashes']} |",
        ]

    out = HERE.parent / "BENCHMARKS.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
